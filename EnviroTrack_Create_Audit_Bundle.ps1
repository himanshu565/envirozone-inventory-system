$ErrorActionPreference = 'Stop'
$Root = 'D:\Projects\inventory\envirozone-inventory-system'

if (-not (Test-Path -LiteralPath (Join-Path $Root 'package.json'))) {
    throw "Could not find package.json at expected repository root: $Root"
}

$timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$stage = Join-Path $env:TEMP "EnviroTrack-audit-$timestamp"
$zip = Join-Path ([Environment]::GetFolderPath('Desktop')) "EnviroTrack-source-audit-$timestamp.zip"
New-Item -ItemType Directory -Path $stage | Out-Null

$excludedDirectoryNames = @(
    '.git', 'node_modules', '.next', 'dist', 'build', 'coverage', '.turbo', '.cache',
    'playwright-report', 'test-results', 'out', 'target'
)
$excludedFileRegex = '^(?i:\.env(?:$|\.).*|.*\.(?:pem|key|p12|pfx)$|id_rsa(?:\.pub)?|credentials(?:\..*)?|secrets?(?:\..*)?)$'

# Include source-bearing directories if present.
$includeDirectories = @('apps', 'packages', 'modules', 'docs', '.github')
foreach ($relativeDir in $includeDirectories) {
    $sourceDir = Join-Path $Root $relativeDir
    if (-not (Test-Path -LiteralPath $sourceDir -PathType Container)) { continue }

    $files = Get-ChildItem -LiteralPath $sourceDir -Recurse -File -Force
    foreach ($file in $files) {
        $relative = $file.FullName.Substring($sourceDir.Length).TrimStart('\','/')
        $segments = $relative -split '[\\/]'
        if ($segments | Where-Object { $_ -in $excludedDirectoryNames }) { continue }
        if ($file.Name -match $excludedFileRegex) { continue }

        $destRelative = Join-Path $relativeDir $relative
        $destFile = Join-Path $stage $destRelative
        $destFolder = Split-Path -Parent $destFile
        New-Item -ItemType Directory -Path $destFolder -Force | Out-Null
        Copy-Item -LiteralPath $file.FullName -Destination $destFile -Force
    }
}

# Include selected root configuration and workspace manifests, but never .env files.
$rootFiles = @(
    'package.json', 'package-lock.json', 'docker-compose.yml', 'docker-compose.yaml',
    '.gitignore', 'README.md', 'README.MD', 'opencode.json', 'opencode.jsonc',
    'tsconfig.json', 'eslint.config.mjs', 'pnpm-workspace.yaml', 'AGENTS.md',
    'EnviroTrack_Implementation_Prompt.md', 'EnviroTrack_Copilot_Implementation_Chain.md'
)
foreach ($name in $rootFiles) {
    $sourceFile = Join-Path $Root $name
    if (-not (Test-Path -LiteralPath $sourceFile -PathType Leaf)) { continue }
    if ($name -match $excludedFileRegex) { continue }
    Copy-Item -LiteralPath $sourceFile -Destination (Join-Path $stage $name) -Force
}


# Add a non-secret Git state summary so the audit can distinguish the current working tree.
$gitReport = Join-Path $stage 'AUDIT_LOCAL_GIT_STATUS.txt'
try {
    $status = & git -C $Root status --short --branch 2>&1
    $diffStat = & git -C $Root diff --stat 2>&1
    $stagedStat = & git -C $Root diff --cached --stat 2>&1
    @(
        'Generated by EnviroTrack_Create_Audit_Bundle.ps1',
        "Repository: $Root",
        "Generated: $(Get-Date -Format o)",
        '',
        '--- git status --short --branch ---',
        ($status | Out-String).TrimEnd(),
        '',
        '--- git diff --stat ---',
        ($diffStat | Out-String).TrimEnd(),
        '',
        '--- git diff --cached --stat ---',
        ($stagedStat | Out-String).TrimEnd(),
        '',
        'Note: Diff contents are intentionally not bundled to reduce risk of including secrets.'
    ) | Set-Content -LiteralPath $gitReport -Encoding utf8
} catch {
    'Git state could not be captured automatically; inspect the working tree locally.' |
        Set-Content -LiteralPath $gitReport -Encoding utf8
}

# Final safety check: ensure no environment/credential files slipped into the bundle.
$unsafe = Get-ChildItem -LiteralPath $stage -Recurse -File -Force | Where-Object {
    $_.Name -match $excludedFileRegex
}
if ($unsafe) {
    Remove-Item -LiteralPath $stage -Recurse -Force
    throw 'Safety check failed: possible secret-bearing files found. Bundle was not created.'
}

Add-Type -AssemblyName System.IO.Compression.FileSystem
[System.IO.Compression.ZipFile]::CreateFromDirectory($stage, $zip, [System.IO.Compression.CompressionLevel]::Optimal, $false)
Remove-Item -LiteralPath $stage -Recurse -Force

Write-Host "Audit bundle created: $zip" -ForegroundColor Green
Write-Host 'Excluded: .git, node_modules, build/cache outputs, all .env files, and common credential/key files.'
Write-Host 'Before uploading, you can inspect the ZIP contents. This script does not change your repository.'
